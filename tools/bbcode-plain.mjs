/**
 * Makes the SQL test that holds the database's plain words to the engine's: supabase/tests/
 * 0116-bbcode-plain.sql, one `do` block asserting, for every fixture in
 * engine/bbcode/plain.fixtures.ts, that `bbcode_plain(body)` (supabase/migrations/0113_search.sql)
 * gives the fixture's `plain` once each run of whitespace is collapsed to one space. The same
 * fixtures are held against `visibleText(parse(body))` by engine/bbcode/plain.test.ts, so the two
 * walks of a post's words are one list in two languages ("Two lists that must agree are one list").
 *
 *   node tools/bbcode-plain.mjs
 *
 * writes the SQL test. tools/check-bbcode-plain.mjs holds the written file to exactly what
 * `sqlTests` makes, and tools/test-bbcode-plain.mjs drives that red.
 *
 * The fixtures are read as text, not imported: the module is TypeScript and the list in it is JSON
 * after PREFIX, the way tools/name-folds.mjs reads engine/rules/name-folds.data.ts.
 */
import fs from 'node:fs';
import { fileURLToPath } from 'node:url';

export const FIXTURES = 'engine/bbcode/plain.fixtures.ts';
export const TESTS = 'supabase/tests/0116-bbcode-plain.sql';
export const PREFIX = 'export const PLAIN_FIXTURES: readonly PlainFixture[] = ';

/** The fixtures, read back from the TypeScript module; a module that is not in the shape is an error. */
export function readFixtures(text) {
  const at = text.indexOf(PREFIX);
  if (at < 0) throw new Error(`${FIXTURES}: no "${PREFIX.trim()}"`);
  const body = text.slice(at + PREFIX.length).trimEnd();
  if (!body.endsWith(';')) throw new Error(`${FIXTURES}: the list does not end with ";"`);
  const list = JSON.parse(body.slice(0, -1));
  if (!Array.isArray(list) || list.length === 0) throw new Error(`${FIXTURES}: the list is empty`);
  const names = new Set();
  for (const f of list) {
    if (typeof f?.name !== 'string' || typeof f.body !== 'string' || typeof f.plain !== 'string') throw new Error(`${FIXTURES}: a fixture without a name, a body and plain words: ${JSON.stringify(f)?.slice(0, 80)}`);
    if (names.has(f.name)) throw new Error(`${FIXTURES}: two fixtures named ${JSON.stringify(f.name)}`);
    names.add(f.name);
  }
  return list;
}

/* Every string goes in a dollar-quoted literal. `$f$` ends one, so a fixture holding it, or ending in a `$` that would
   join it, cannot be written; the generator says so rather than writing a file that means something else. */
const TAG = '$f$';
const quoted = (s, what) => {
  if (s.includes(TAG) || s.endsWith('$')) throw new Error(`${FIXTURES}: ${what} holds "${TAG}" or ends in "$", which a dollar-quoted literal cannot carry`);
  return `${TAG}${s}${TAG}`;
};

/** The text of the SQL test for these fixtures. */
export function sqlTests(fixtures) {
  const rows = fixtures.map((f) => `    (${quoted(f.name, `the name ${JSON.stringify(f.name)}`)}, ${quoted(f.body, `the body of ${JSON.stringify(f.name)}`)}, ${quoted(f.plain, `the plain words of ${JSON.stringify(f.name)}`)})`);
  return [
    `-- Generated by tools/bbcode-plain.mjs from ${FIXTURES}. Do not edit by hand: tools/check-bbcode-plain.mjs fails the build on any difference.`,
    '-- bbcode_plain (supabase/migrations/0113_search.sql) mirrors engine/bbcode/visible.ts over engine/bbcode/parse.ts; this holds it to the words',
    '-- the engine gives for each fixture, with each run of whitespace collapsed to one space (a separator is only a word boundary to the index).',
    '',
    'do $test$',
    'declare',
    '  f record;',
    '  got text;',
    'begin',
    '  for f in',
    '    select * from (values',
    rows.join(',\n'),
    '    ) as v (name, body, plain)',
    '  loop',
    "    got := btrim(regexp_replace(bbcode_plain(f.body), '[\\u0009-\\u000d ]+', ' ', 'g'), ' ');",
    '    if got is distinct from f.plain then',
    "      raise exception 'bbcode_plain: fixture \"%\" gave %, wanted %', f.name, to_json(got), to_json(f.plain);",
    '    end if;',
    '  end loop;',
    'end',
    '$test$;',
    '',
  ].join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const fixtures = readFixtures(fs.readFileSync(FIXTURES, 'utf8'));
  fs.writeFileSync(TESTS, sqlTests(fixtures));
  console.log(`wrote ${TESTS}: ${fixtures.length} fixtures`);
}
