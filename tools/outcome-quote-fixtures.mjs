/**
 * Makes the SQL test that holds the database's outcome quote to the engine's: supabase/tests/0452-outcome-quotes-parity.sql,
 * one `do` block asserting, for every case in engine/bbcode/outcome-quote.fixtures.ts, that `outcome_quote(post, room)`
 * (supabase/migrations/0452_outcome_quotes.sql) gives `[quote=<post>]<words>[/quote]` and a line break, or null where the
 * case's words are null. The same cases are held against `outcomeQuote` by engine/bbcode/outcome-quote.test.ts and
 * engine/ui/data/fake.test.tsx, so the two are one list in two languages ("Two lists that must agree are one list").
 *
 *   node tools/outcome-quote-fixtures.mjs
 *
 * writes the SQL test. tools/check-outcome-quote-fixtures.mjs holds the written file to exactly what `sqlTests` makes, and
 * tools/test-outcome-quote-fixtures.mjs drives that red. The fixtures are read as text, not imported: the module is
 * TypeScript and the list in it is JSON after PREFIX, the way tools/bbcode-plain.mjs reads engine/bbcode/plain.fixtures.ts.
 */
import fs from 'node:fs';
import { fileURLToPath } from 'node:url';

export const FIXTURES = 'engine/bbcode/outcome-quote.fixtures.ts';
export const TESTS = 'supabase/tests/0452-outcome-quotes-parity.sql';
export const PREFIX = 'export const OUTCOME_QUOTE_FIXTURES: readonly OutcomeQuoteFixture[] = ';

/** The cases, read back from the TypeScript module; a module that is not in the shape is an error. */
export function readFixtures(text) {
  const at = text.indexOf(PREFIX);
  if (at < 0) throw new Error(`${FIXTURES}: no "${PREFIX.trim()}"`);
  const body = text.slice(at + PREFIX.length).trimEnd();
  if (!body.endsWith(';')) throw new Error(`${FIXTURES}: the list does not end with ";"`);
  const list = JSON.parse(body.slice(0, -1));
  if (!Array.isArray(list) || list.length === 0) throw new Error(`${FIXTURES}: the list is empty`);
  const names = new Set();
  for (const f of list) {
    if (typeof f?.name !== 'string' || typeof f.body !== 'string') throw new Error(`${FIXTURES}: a case without a name and a body: ${JSON.stringify(f)?.slice(0, 80)}`);
    if (!Number.isInteger(f.room)) throw new Error(`${FIXTURES}: the room of ${JSON.stringify(f.name)} is not a whole number`);
    if (f.words !== null && typeof f.words !== 'string') throw new Error(`${FIXTURES}: the words of ${JSON.stringify(f.name)} are neither a string nor null`);
    if (names.has(f.name)) throw new Error(`${FIXTURES}: two cases named ${JSON.stringify(f.name)}`);
    names.add(f.name);
  }
  return list;
}

/* Every string goes in a dollar-quoted literal; `$f$` ends one, so a case holding it, or ending in a `$` that would join it, cannot be written. */
const TAG = '$f$';
const quoted = (s, what) => {
  if (s.includes(TAG) || s.endsWith('$')) throw new Error(`${FIXTURES}: ${what} holds "${TAG}" or ends in "$", which a dollar-quoted literal cannot carry`);
  return `${TAG}${s}${TAG}`;
};

/** The text of the SQL test for these cases. */
export function sqlTests(fixtures) {
  const rows = fixtures.map((f) => `    (${quoted(f.name, `the name ${JSON.stringify(f.name)}`)}, ${quoted(f.body, `the body of ${JSON.stringify(f.name)}`)}, ${f.room}, ${f.words === null ? 'null' : quoted(f.words, `the words of ${JSON.stringify(f.name)}`)})`);
  return [
    `-- Generated by tools/outcome-quote-fixtures.mjs from ${FIXTURES}. Do not edit by hand: tools/check-outcome-quote-fixtures.mjs fails the build on any difference.`,
    '-- outcome_quote (supabase/migrations/0452_outcome_quotes.sql) is engine/bbcode/outcome-quote.ts in plain SQL; this holds it to the words the engine gives for each case:',
    '-- a post with the case\'s body, quoted with the case\'s room, is `[quote=<post>]<words>[/quote]` and a line break, or null where the room leaves no quote.',
    '-- `{Q}` in a body is the id of another post, so a case can open with a real quote.',
    '',
    'do $test$',
    'declare',
    '  f record;',
    '  t uuid := tests.thread(\'Outcome quote parity\');',
    '  c uuid := tests.character(tests.account(\'oq-parity\'), \'Oq Parity\');',
    '  q uuid := tests.post(c, t, \'first words\');',
    '  p uuid;',
    '  got text;',
    'begin',
    '  for f in',
    '    select * from (values',
    rows.join(',\n'),
    '    ) as v (name, body, room, words)',
    '  loop',
    "    p := tests.post(c, t, replace(f.body, '{Q}', q::text));",
    '    got := outcome_quote(p, f.room);',
    "    if got is distinct from (case when f.words is null then null else '[quote=' || p || ']' || f.words || E'[/quote]\\n' end) then",
    "      raise exception 'outcome_quote: case \"%\" gave %, wanted %', f.name, to_json(got), to_json(f.words);",
    '    end if;',
    '  end loop;',
    'end',
    '$test$;',
    '',
  ].join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const fixtures = readFixtures(fs.readFileSync(FIXTURES, 'utf8'));
  fs.writeFileSync(TESTS, sqlTests(fixtures));
  console.log(`wrote ${TESTS}: ${fixtures.length} cases`);
}
