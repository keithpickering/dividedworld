/**
 * Makes the SQL test that holds the database's phrase matcher to the engine's: supabase/tests/0136-phrase.sql,
 * one `do` block asserting, for every fixture in engine/bbcode/phrase.fixtures.ts, that
 * `phrase_in(bbcode_plain(body), phrase)` (supabase/migrations/0139_face_down_moves.sql over 0117_search.sql) gives the
 * fixture's `found`. The same fixtures are held against `phraseIn(visibleText(parse(body)), phrase)` by
 * engine/bbcode/phrase.test.ts, so the two matchers are one list in two languages ("Two lists that must agree are one list").
 *
 *   node tools/phrase-sql.mjs
 *
 * writes the SQL test. tools/check-phrase-sql.mjs holds the written file to exactly what `sqlTests` makes, and
 * tools/test-phrase-sql.mjs drives that red.
 *
 * The fixtures are read as text, not imported: the module is TypeScript and the list in it is JSON after PREFIX, the way
 * tools/bbcode-plain.mjs reads engine/bbcode/plain.fixtures.ts.
 */
import fs from 'node:fs';
import { fileURLToPath } from 'node:url';

export const FIXTURES = 'engine/bbcode/phrase.fixtures.ts';
export const TESTS = 'supabase/tests/0136-phrase.sql';
export const PREFIX = 'export const PHRASE_FIXTURES: readonly PhraseFixture[] = ';

/** The fixtures, read back from the TypeScript module; a module that is not in the shape is an error. */
export function readFixtures(text) {
  const at = text.indexOf(PREFIX);
  if (at < 0) throw new Error(`${FIXTURES}: no "${PREFIX.trim()}"`);
  const body = text.slice(at + PREFIX.length).trimEnd();
  if (!body.endsWith(';')) throw new Error(`${FIXTURES}: the list does not end with ";"`);
  const list = JSON.parse(body.slice(0, -1));
  if (!Array.isArray(list) || list.length === 0) throw new Error(`${FIXTURES}: the list is empty`);
  const names = new Set();
  for (const f of list) {
    if (typeof f?.name !== 'string' || typeof f.body !== 'string' || typeof f.phrase !== 'string' || typeof f.found !== 'boolean') {
      throw new Error(`${FIXTURES}: a fixture without a name, a body, a phrase and a found: ${JSON.stringify(f)?.slice(0, 80)}`);
    }
    if (names.has(f.name)) throw new Error(`${FIXTURES}: two fixtures named ${JSON.stringify(f.name)}`);
    names.add(f.name);
  }
  return list;
}

/* Every string goes in a dollar-quoted literal. `$f$` ends one, so a fixture holding it, or ending in a `$` that would
   join it, cannot be written; the generator says so rather than writing a file that means something else. */
const TAG = '$f$';
const quoted = (s, what) => {
  if (s.includes(TAG) || s.endsWith('$')) throw new Error(`${FIXTURES}: ${what} holds "${TAG}" or ends in "$", which a dollar-quoted literal cannot carry`);
  return `${TAG}${s}${TAG}`;
};

/** The text of the SQL test for these fixtures. */
export function sqlTests(fixtures) {
  const rows = fixtures.map((f) => `    (${quoted(f.name, `the name ${JSON.stringify(f.name)}`)}, ${quoted(f.body, `the body of ${JSON.stringify(f.name)}`)}, ${quoted(f.phrase, `the phrase of ${JSON.stringify(f.name)}`)}, ${f.found})`);
  return [
    `-- Generated by tools/phrase-sql.mjs from ${FIXTURES}. Do not edit by hand: tools/check-phrase-sql.mjs fails the build on any difference.`,
    '-- phrase_in (supabase/migrations/0139_face_down_moves.sql) asks of a post\'s plain words (bbcode_plain, 0117) what engine/bbcode/phrase.ts asks of',
    '-- visibleText(parse(body)): whether the phrase is there as a whole word, case-folded as JavaScript folds it. This holds it to the answer the engine gives',
    '-- for each fixture.',
    '',
    'do $test$',
    'declare',
    '  f record;',
    '  got boolean;',
    'begin',
    '  for f in',
    '    select * from (values',
    rows.join(',\n'),
    '    ) as v (name, body, phrase, found)',
    '  loop',
    '    got := phrase_in(bbcode_plain(f.body), f.phrase);',
    '    if got is distinct from f.found then',
    "      raise exception 'phrase_in: fixture \"%\" gave %, wanted %', f.name, got, f.found;",
    '    end if;',
    '  end loop;',
    'end',
    '$test$;',
    '',
  ].join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const fixtures = readFixtures(fs.readFileSync(FIXTURES, 'utf8'));
  fs.writeFileSync(TESTS, sqlTests(fixtures));
  console.log(`wrote ${TESTS}: ${fixtures.length} fixtures`);
}
