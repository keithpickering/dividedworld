def face(k,extra=''):
    cls,al,play,rar,name,text,foot=CARDS[k]
    c='' if cls=='sweet' else cls
    return f'''<div class="pc {c}" {extra}><div class="row"><div><span class="al">{al}</span><br><span class="play">{play}</span></div><div class="gem {rar}" title="{rar}"></div></div>
<div class="art"><img src="{ART}{k}.svg" alt=""></div><h3{' style="font-size:30px"' if len(name)>10 else ''}>{name.upper()}</h3><p>{text}</p><footer><span>POSTCARD</span><span>{foot}</span></footer></div>'''
def back(hit=False,extra=''):
    return f'<div class="back{" hit" if hit else ""}" {extra}><div class="seal"><b>{"HIT" if hit else "?"}</b></div></div>'
