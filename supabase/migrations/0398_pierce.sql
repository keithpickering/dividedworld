-- ---- 4. card_ended ----

-- card_ended (0149), also true for a play a cast spent: a pierce play is spent by the cast that names it (`pierce.by`): it is over, as an ended play is, for every reader. One probe of acts_pierce_by.
create or replace function card_ended(play uuid) returns boolean
