         coalesce((select jsonb_agg(jsonb_build_object('board', b.board, 'move', b.move_act, 'group', b."group", 'expires_at', b.expires_at) order by b.board, b.move_act)
                   from bars_of(c.id) b), '[]'::jsonb) as bars,
         (select max(r.at) from class_reveals r where r.character = c.id and r.class = h.class_key and r.at >= h.started_at) as class_shown_at,
         coalesce((select jsonb_agg(jsonb_build_object('thread', l.thread, 'until', l.ends) order by l.ends, l.thread)
                   from (select s.thread, lockout_ends(s.id) as ends from acts s
                         where s.kind = 'spring' and s.payload ->> 'did' = 'lockedOut' and s.payload ->> 'locks' = c.id::text) l
                   where l.ends > now()), '[]'::jsonb) as lockouts
  from characters c
  cross join lateral (select x.class_key, x.started_at, x.due_at from class_history x where x.character = c.id order by x.started_at desc limit 1) h
  cross join lateral (
    select (select max(x.started_at) from class_history x
            where x.character = c.id and x.started_at > (select min(f.started_at) from class_history f where f.character = c.id))
           + span_interval((select s.value from settings s where s.key = 'turnCooldown')) as at
  ) t
  left join pending_turns p on p.character = c.id
  where c.owner = auth.uid();

-- ---- 14. pool_context ----

-- pool_context (0339_thread_places_at_scale), a `lockouts` key: [{ staff, thread }] for each staff persona's live lockout. Everything else as 0339 wrote it; its grants are as they were.
create or replace function pool_context() returns jsonb
language sql stable security definer set search_path = public, pg_temp as $$
  select jsonb_build_object(
    'season', (select jsonb_build_object('startsAt', (extract(epoch from s.starts_at) * 1000)::bigint,
        'endsAt', (extract(epoch from coalesce(s.ends_at, s.starts_at + span_interval(setting('seasonLength')))) * 1000)::bigint)
      from seasons s where s.ends_at is null order by s.starts_at desc limit 1),
    'boss', current_boss(),
    'predecessor', (select h.outgoing from season_handovers h
                    where h.boss = current_boss() and h.outgoing is distinct from h.boss order by h.landed_at desc, h.season desc limit 1),
    'offices', coalesce((select jsonb_object_agg(o.staff, o.office) from staff_office_now o join characters c on c.staff = o.staff where c.staff_kind = 'persona'), '{}'::jsonb),
    'characters', coalesce((select jsonb_object_agg(c.staff, c.id) from characters c where c.staff is not null and c.staff_kind = 'persona'), '{}'::jsonb),
    'boards', coalesce((select jsonb_object_agg(b.id, b.slug) from boards b where not b.is_system and board_is_open(b.id)), '{}'::jsonb),
    -- Each persona's live lockouts, public as the springs are: the chatter offers no reply or card in a thread its persona is locked out of, so no paid answer goes to a post that would be refused. `staff` is the persona's
    -- character id (the values of `characters` above) and `thread` the thread, both text.
    'lockouts', coalesce((select jsonb_agg(jsonb_build_object('staff', c.id::text, 'thread', s.thread::text) order by s.created_at, s.id)
                          from characters c join acts s on s.kind = 'spring' and s.payload ->> 'did' = 'lockedOut' and s.payload ->> 'locks' = c.id::text
                          where c.staff is not null and c.staff_kind = 'persona' and lockout_ends(s.id) > now()), '[]'::jsonb))
$$;;
