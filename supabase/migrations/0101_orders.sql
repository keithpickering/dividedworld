-- Orders, beats, allowances and the Mods' memory (the Mod Bots design, sections 2 and 3; its plan, Task 4).
--
-- The Boss's meeting hands each Mod on staff an order: the boards it watches (its beat), one line in the Boss's voice, and an allowance, a number of
-- moves out of the Boss's own bank. `staff_orders` is the append-only log of them; the latest per Mod is in force. A Mod spends its allowance when its
-- move is queued (`mod_allowance` counts what is left); what it has not spent returns to the Boss's bank at the next meeting, before the meeting reads
-- the bank, never above the phase's cap, and exactly once: every applied meeting writes a new order for every Mod that has one (an answer that leaves
-- a Mod out carries its beat and line forward with an allowance of 0), so no order is ever returned twice, and a meeting that fails writes and
-- returns nothing (apply_meeting is one transaction, and a closed meeting is never applied again).
--
-- Beats: every board is on exactly one Mod's beat, and the answer need not say so. `beat_of(board)` is the Mod whose latest order names the board;
-- else, among the Mods on staff, the one whose persona prefers the board's slug (`staff_beats`, seeded from each persona's `beats`), then the one
-- with the fewest boards, then the first by key. It answers whenever a Mod is on staff. It reads the Mods on staff (a handful, bounded by the roster)
-- and each one's latest order by (staff, id desc), never a scan of boards or Acts, so it is cheap to call on every rule-breaking post.
--
-- Ways out: nothing here holds a player. An allowance that is not spent returns to the Boss; a Mod that leaves the staff has its unspent allowance
-- returned at the next meeting; a Mod's rule that is refused or held spends nothing.

-- ------------------------------------------------------------------------------------------------- beat preferences ----

-- The kinds of board (slugs) a persona likes to watch, from the seed (`Persona.beats`). Not an Act: the instance's own content, replaced by a reseed.
create table staff_beats (
  staff text not null references characters (staff),
  slug text not null check (slug <> ''),
  primary key (staff, slug)
);
alter table staff_beats enable row level security;
revoke all on staff_beats from public, anon, authenticated;

-- --------------------------------------------------------------------------------------------------------- orders ----

create table staff_orders (
  id bigint generated always as identity primary key,
  meeting bigint not null references meetings (id),
  staff text not null references characters (staff),
  -- The boards it watches: the player boards the meeting named for it, and no board twice in one meeting's orders.
  boards uuid[] not null default '{}',
  -- One line in the Boss's voice, read by that Mod's calls until the next meeting. Shown, never acted on.
  order_line text not null check (char_length(order_line) <= 200),
  -- Moves handed out of the Boss's bank: a whole number, at most `modBots.allowanceMost` (held by apply_meeting).
  allowance integer not null check (allowance >= 0),
  -- The highest queued_moves id when this order was written: a Mod's moves after it are spent against this allowance.
  last_move bigint not null,
  at timestamptz not null default now(),
  unique (meeting, staff)
);
create index staff_orders_latest on staff_orders (staff, id desc);
alter table staff_orders enable row level security;
revoke all on staff_orders from public, anon, authenticated;

create function staff_orders_append_only() returns trigger
language plpgsql set search_path = public, pg_temp as $$
begin
  raise exception 'an order is never edited or removed (%); write a new one', tg_op using errcode = 'P0001';
end $$;
create trigger staff_orders_no_update before update or delete on staff_orders for each row execute function staff_orders_append_only();
create trigger staff_orders_no_truncate before truncate on staff_orders for each statement execute function staff_orders_append_only();
-- Always: a session in replica mode, as a restore with triggers disabled runs, fires them too.
alter table staff_orders enable always trigger staff_orders_no_update;
alter table staff_orders enable always trigger staff_orders_no_truncate;
revoke execute on function staff_orders_append_only() from public, anon, authenticated;

-- A Mod's moves are counted by staff and id: the allowance left is one range count on this.
create index queued_moves_staff on queued_moves (staff, id);

-- ----------------------------------------------------------------------------------------------------- allowances ----

-- What the latest order handed a persona, less the moves it queued since. A rule the tick refused at landing (`refused_at`) and one an admin held
-- (`held_at`) spend nothing; a move that failed to land for a reason that may pass is tried again and stays spent. Whether the persona is still a Mod
-- is no business of this: apply_meeting returns an unspent allowance even from one that has left the staff.
create function order_unspent(who text) returns integer
language sql stable security definer set search_path = public, pg_temp as $$
  select coalesce((
    select greatest(0, o.allowance - (select count(*) from queued_moves q where q.staff = o.staff and q.id > o.last_move and q.refused_at is null and q.held_at is null))::integer
    from staff_orders o where o.staff = who order by o.id desc limit 1), 0)
$$;
revoke execute on function order_unspent(text) from public, anon, authenticated;
grant execute on function order_unspent(text) to service_role;

-- The moves a Mod on staff may still queue; zero for anyone else.
create function mod_allowance(staff text) returns integer
language sql stable security definer set search_path = public, pg_temp as $$
  select case when exists (select 1 from staff_now n where n.staff = mod_allowance.staff) then order_unspent(mod_allowance.staff) else 0 end
$$;
revoke execute on function mod_allowance(text) from public, anon, authenticated;
grant execute on function mod_allowance(text) to service_role;

-- ---------------------------------------------------------------------------------------------------------- beats ----

-- The Mod on whose beat a board is. Null only when no Mod is on staff.
create function beat_of(board uuid) returns text
language sql stable security definer set search_path = public, pg_temp as $$
  select m.staff
  from (
    select n.staff, coalesce(o.boards, '{}') as boards,
           exists (select 1 from staff_beats b where b.staff = n.staff and b.slug = (select s.slug from boards s where s.id = beat_of.board)) as likes
    from staff_now n
    left join lateral (select x.boards from staff_orders x where x.staff = n.staff order by x.id desc limit 1) o on true
  ) m
  order by coalesce(beat_of.board = any (m.boards), false) desc, m.likes desc, cardinality(m.boards), m.staff
  limit 1
$$;
revoke execute on function beat_of(uuid) from public, anon, authenticated;
grant execute on function beat_of(uuid) to service_role;


