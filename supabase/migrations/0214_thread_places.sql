-- A thread's stored board, and moves that last (docs/plans/2026-11-06-fangame-split-design.md, section 4; docs/plans/2026-11-06-fangame-split-plan.md, Task 1).
--
-- Moves so far all end: by their demand, their expiry, or an admin. The fangame split adds moves that build something which stays (a board made, a board
-- merged, a thread moved). A kind says so in `move_kinds.lasting`, seeded from the engine's catalog (MoveKind.lasting); a lasting kind has no expiry and carries
-- no demand, and ends only by being reversed or superseded.
--
--   move_kinds.lasting          not null, false for every kind there is today. seed_instance (0149) also writes it, from the catalog's flag.
--   threads.origin_board        where a thread was started: backfilled from board, then required, and never changed (an update trigger refuses it, enabled
--                               always). A before-insert trigger fills it from `board` when an insert does not say, so the dozen places that start a thread
--                               (start_thread and spin, in every version of them, and the announcements threads) need no change and a later one cannot forget it.
--   threads.board               stays the column every reader reads, now commented as derived: where the thread is now, written only by a rebuild (below),
--                               the way open_moves.progress is derived (0053).
--   thread_place(thread)        the board a thread is on, computed from its origin and the lasting moves in force, in the order they landed: a thread whose
--                               origin board was made by a createBoard that has been reversed starts on that move's `fallback` param, else the instance's
--                               first open non-system board; then the latest moveThread in force that names it (params.thread, params.board) places it;
--                               then, until the board is open, any mergeBoard in force of that board (params.board, params.into) sends it on. Null for no such thread.
--                               The three kinds land in the next task; this reads them as the design states them, and with none in force it is the origin.
--   board_is_open(board)        a board is open unless a mergeBoard of it is in force or the createBoard that made it has been reversed.
--   rebuild_thread_places(which) writes board = thread_place(id) where they differ, for the named threads or all; returns how many rows it changed.
--   thread_places_drift()       the threads whose stored board is not the computed one: thread, stored, rebuilt. A test holds it empty.
--   boards.created_by_act       the move Act that made a board (null for the boards seeded or made before), so a reversed createBoard is found from the board.
--                               The plan puts this column in the next task; thread_place needs it now, so it is here and the next task adds nothing but its guard.
--   inheritance_due (0051)      leaves out a lasting move (`and not k.lasting`): a new Boss reviews moves that expire, and a board built to stay is not undone by a handover.
--
-- end_move (0135) is not changed here: which threads a lasting move's end rebuilds depends on the kinds, so the task that adds them does it.
--
-- Cost on a busy instance: a board's page is still one indexed read of threads.board. open_moves is NOT small once lasting moves never expire, and this migration's
-- thread_place scans it per thread; 0215 makes the rebuild and the drift set-based and thread_place indexed, and supersedes this reading of what is in force (any move_end
-- ends a lasting move, not only a reversal). A move's landing rebuilds only the threads it touches.
-- Masks. A thread's board is public, and nothing here is computed from who owns a character, a class or a reaction.
-- Ways out. No state is added for a player: a thread that is moved can be moved back by an admin, and every lasting move ends by reversal.
-- Append-only. No Act is touched: a thread's board is derived from the Acts, and origin_board is the one fact about a thread that is written once.
-- All three functions are for service_role and the tick alone.
--
-- Ported onto main (merge of #449 Cosmetics, migrations 0205-0213): seed_instance: rebuilt on 0207's body (main's gear, eventLines and trophies sections kept beside this migration's own).

