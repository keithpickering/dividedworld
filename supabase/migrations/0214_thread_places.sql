create function threads_origin_default() returns trigger
language plpgsql set search_path = public, pg_temp as $$
begin
  new.origin_board := coalesce(new.origin_board, new.board);
  return new;
end $$;
create trigger threads_origin_default before insert on threads for each row execute function threads_origin_default();

create function threads_origin_fixed() returns trigger
language plpgsql set search_path = public, pg_temp as $$
begin
  raise exception 'a thread''s origin_board never changes; its board is derived from it and the lasting moves in force' using errcode = 'P0001';
end $$;
create trigger threads_origin_fixed before update of origin_board on threads for each row
  when (old.origin_board is distinct from new.origin_board) execute function threads_origin_fixed();
-- Always: a session in replica mode, as a restore with triggers disabled runs, fires it too.
alter table threads enable always trigger threads_origin_fixed;

