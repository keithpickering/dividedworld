-- A board is open unless a mergeBoard of it is in force, or the createBoard that made it has been reversed.
create function board_is_open(in_board uuid) returns boolean
language sql stable security definer set search_path = public, pg_temp as $$
  select not exists (
    select 1 from open_moves o join acts a on a.id = o.move_act
    where a.payload ->> 'kind' = 'mergeBoard' and lower(a.payload #>> '{params,board}') = in_board::text
  ) and not exists (
    select 1 from boards b join acts e on e.kind = 'move_end' and e.target_act_id = b.created_by_act and e.payload ->> 'why' = 'reversed'
    where b.id = in_board
  )
$$;

-- Where a thread is, from its origin and the lasting moves in force (see the header).
create function thread_place(in_thread uuid) returns uuid
language plpgsql stable security definer set search_path = public, pg_temp as $$
declare
  here uuid;
  moved text;
  hop uuid;
  made uuid;
  fallback uuid;
  steps integer := 0;
begin
  select t.origin_board into here from threads t where t.id = in_thread;
  if here is null then return null; end if;
  -- The latest moveThread in force that names the thread places it, whatever its origin was.
  select lower(a.payload #>> '{params,board}') into moved
  from open_moves o join acts a on a.id = o.move_act
  where a.payload ->> 'kind' = 'moveThread' and lower(a.payload #>> '{params,thread}') = in_thread::text
  order by a.created_at desc, a.id desc limit 1;
  if moved is not null then here := moved::uuid; end if;
  -- Until the board is open: a merge in force sends the thread into the board it names; a board whose creation was reversed sends it to that move's fallback
  -- (else the first open board that is not The System's). A chain is followed; a cycle or a very long chain stops where it is.
  while steps < 50 and not board_is_open(here) loop
    steps := steps + 1;
    select lower(a.payload #>> '{params,into}')::uuid into hop
    from open_moves o join acts a on a.id = o.move_act
    where a.payload ->> 'kind' = 'mergeBoard' and lower(a.payload #>> '{params,board}') = here::text
    order by a.created_at desc, a.id desc limit 1;
    if hop is null then
      select b.created_by_act into made from boards b where b.id = here;
      select lower(a.payload #>> '{params,fallback}')::uuid into fallback from acts a where a.id = made;
      hop := coalesce((select b.id from boards b where b.id = fallback and b.id <> here),
                      (select b.id from boards b where not b.is_system and b.id <> here and board_is_open(b.id) order by b.created_at, b.id limit 1));
    end if;
    exit when hop is null or hop = here;
    here := hop;
  end loop;
  return here;
end $$;

create function rebuild_thread_places(which uuid[] default null) returns integer
language plpgsql security definer set search_path = public, pg_temp as $$
declare
  changed integer;
begin
  with placed as (
    select t.id, thread_place(t.id) as board from threads t where which is null or t.id = any (which)
  ), written as (
    update threads t set board = p.board from placed p where t.id = p.id and p.board is not null and t.board is distinct from p.board returning 1
  )
  select count(*)::integer into changed from written;
  return changed;
end $$;

create function thread_places_drift() returns table (thread uuid, stored uuid, rebuilt uuid)
language sql stable security definer set search_path = public, pg_temp as $$
  select t.id, t.board, thread_place(t.id) from threads t where t.board is distinct from thread_place(t.id)
$$;

revoke execute on function threads_origin_default(), threads_origin_fixed() from public, anon, authenticated;
revoke execute on function board_is_open(uuid), thread_place(uuid), rebuild_thread_places(uuid[]), thread_places_drift() from public, anon, authenticated;
grant execute on function board_is_open(uuid), thread_place(uuid), rebuild_thread_places(uuid[]), thread_places_drift() to service_role;

