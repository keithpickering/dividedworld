-- inheritance_due (0051), leaving out a lasting move. Everything else as 0051 wrote it.
create or replace function inheritance_due(for_boss text, cap integer default 100) returns table (act uuid, thread uuid, payload jsonb, landed_at timestamptz, author text, board_name text)
language sql stable security definer set search_path = public, pg_temp as $$
  select a.id, a.thread, a.payload, a.created_at, c.name,
         (select b.name from boards b where lower(a.payload #>> '{params,board}') = b.id::text)
  from open_moves o
  join acts a on a.id = o.move_act
  join characters c on c.id = a.character
  join move_kinds k on k.key = a.payload ->> 'kind' and k.shapes_board and not k.lasting
  where inheritance_due.for_boss is not null and move_owner(a.id) is distinct from inheritance_due.for_boss
  order by a.created_at, a.id
  limit inheritance_due.cap
$$;

